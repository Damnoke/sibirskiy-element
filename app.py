# 1. БАЗЫ ЗНАНИЙ
# ============================================================
JOKES = [
    "Анекдот: Приходит пациент в аптеку и спрашивает: «У вас есть что-нибудь от жадности?» Аптекарь: «Конечно, вот рецепт на бесплатный сыр».",
    "Шутка: Мой искусственный интеллект работает так быстро, что иногда сам себя обгоняет.",
    "Анекдот: В аптеке: «У вас есть таблетки от головы?» — «Есть, но они не от вашей головы»."
]
FACTS = [
    "Факт: Человеческое сердце бьётся около 100 тысяч раз в сутки.",
    "Факт: В теле человека столько железа, что из него можно сделать гвоздь."
]
GREETINGS = ["Привет! Чем могу помочь?", "Здравствуйте! Слушаю вас.", "Приветствую!"]
IDENTITY = ["Я — искусственный интеллект аптеки «Сибирский Элемент». Моя задача — помогать людям и следить за безопасностью."]

MED_DB = {
    "цитрамон": {"name": "Цитрамон", "b2b": "1 таблетка 2–3 раза в день после еды.", "b2c": "Принимайте по 1 таблетке. Проконсультируйтесь с врачом!"},
    "капотен": {"name": "Капотен", "b2b": "1 таблетка (25 мг) под язык.", "b2c": "Положите под язык. Проконсультируйтесь с врачом! Если не полегчает — вызывайте скорую."},
    "терафлю": {"name": "Терафлю", "b2b": "1 пакетик растворить в горячей воде.", "b2c": "Разведите пакетик в воде. Проконсультируйтесь с врачом!"}
}

def find_drug(phrase):
    p_low = phrase.lower()
    for key in MED_DB:
        if key in p_low: return MED_DB[key]
    names = list(MED_DB.keys())
    for w in re.findall(r"[а-яё]+", p_low):
        matches = difflib.get_close_matches(w, names, n=1, cutoff=0.6)
        if matches: return MED_DB[matches[0]]
    return None

