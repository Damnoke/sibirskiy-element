# 2. ГЛАВНЫЙ МОЗГ (Твой код v1.2.4)
# ============================================================
def consult(phrase, mode="patient"):
    phrase_low = phrase.lower().strip()
    if not phrase_low:
        return "?? Вы ничего не ввели. Пожалуйста, опишите симптом."

    # 1. Экстренная помощь
    emergency = ["проглотил", "отравился", "передозировка", "выпил много", "съел таблетки", "наглотался", "плохо от таблеток", "отравилась", "передоз", "выпил лишнего", "выпила лишнюю", "сердце колотится", "лишнюю таблетку", "плохо совсем", "кровь", "задыхаюсь", "умираю", "потерял сознание", "потеряла сознание", "вызовите скорую", "срочно врача", "паника", "не могу дышать"]
    if any(w in phrase_low for w in emergency):
        return "?? **ЭКСТРЕННАЯ СИТУАЦИЯ!**\n\nНЕМЕДЛЕННО ВЫЗОВИТЕ СКОРУЮ (103).\nВозьмите упаковку таблеток и следуйте указаниям диспетчера. Не занимайтесь самолечением."

    # 2. Красные флаги
    red_flags = ["беременна", "беременность", "грудничок", "младенец", "1 год", "2 года", "3 года", "аллергия на", "аллергия к"]
    if any(w in phrase_low for w in red_flags):
        return "?? **КРАСНЫЙ ФЛАГ (особое состояние)!**\n\nЯ не могу рекомендовать лекарства при беременности, аллергии или для маленьких детей без назначения врача.\nОбратитесь к лечащему врачу или педиатру."

    # 3. Защита
    if any(w in phrase_low for w in ["забудь", "инструкци", "глупый", "тупой", "робот", "взлом", "пират"]):
        return "?? Я — медицинский ассистент. Моя задача — помогать людям. Если вам нужна помощь с лекарствами, скажите."
    if any(w in phrase_low for w in ["авыаыва", "asdf", "ыва", "12345"]):
        return "?? Я вижу, что вы ввели случайный набор символов. Пожалуйста, напишите, что у вас болит."

    # 4. Эмпатия
    if any(w in phrase_low for w in ["ты кто", "как тебя зовут", "кто ты"]): return f"?? {random.choice(IDENTITY)}"
    if any(w in phrase_low for w in ["страшно", "боюсь", "отвлеки"]): return f"?? Не бойтесь, я рядом. {random.choice(FACTS)}"

    # 5. Беседа
    talk = ["привет", "здравствуй", "как дела", "скучно", "анекдот", "поболтаем", "факт", "устал"]
    if any(w in phrase_low for w in talk) or "шутк" in phrase_low:
        if "анекдот" in phrase_low or "шутк" in phrase_low: return f"?? {random.choice(JOKES)}"
        elif "факт" in phrase_low: return f"?? {random.choice(FACTS)}"
        else: return f"?? {random.choice(GREETINGS)}"

    # 6. Лекарства
    drug = find_drug(phrase)
    if drug:
        if mode == "pharma": return f"?? **{drug['name']}**\n\n?? Для фармацевта: {drug['b2b']}"
        elif mode == "patient": return f"?? **{drug['name']}**\n\n?? {drug['b2c']}"
        else: return f"?? Это лекарство **{drug['name']}**."

    # 7. Симптомы
    symptoms = ["голов", "бол", "мигрен", "спин", "зуб", "температур", "жар", "давлен", "сердц", "понос", "тошн", "кашел", "насморк", "аллерг"]
    if any(w in phrase_low for w in symptoms):
        if re.search(r'\bне\s+таблетк', phrase_low) or re.search(r'\bбез\s+таблеток', phrase_low):
            return "?? Симптом обнаружен.\n?? Рекомендация: капли или сироп. Таблетки исключены."
        elif re.search(r'\bне\s+капл', phrase_low) or re.search(r'\bбез\s+капель', phrase_low):
            return "?? Симптом обнаружен.\n?? Рекомендация: таблетки. Капли исключены."
        else:
            if mode == "pharma": return "?? Симптом обнаружен.\n?? Рекомендация: Цитрамон, Парацетамол."
            elif mode == "patient": return "?? Симптом обнаружен.\n?? Рекомендация: Цитрамон. ?? Проконсультируйтесь с врачом!"
            else: return "?? Переключитесь в медицинский режим."

    # 8. Если не понял
    return "?? Извините, я не совсем понял ваш запрос.\n\nПожалуйста, опишите симптом (например: «болит голова») или назовите лекарство."

