# 3. ИНТЕРФЕЙС САЙТА (STREAMLIT)
# ============================================================
st.title("?? Сибирский Элемент v1.2.5")
st.markdown("### Умный ИИ-ассистент для аптек, пациентов и приятной беседы")

# Выбор режима в боковой панели
mode_label = st.sidebar.radio(
    "Выберите режим работы:",
    ["????? Фармацевт", "???????? Пациент", "?? Поболтать"]
)

# Определяем режим для кода
mode = "pharma" if "Фармацевт" in mode_label else ("patient" if "Пациент" in mode_label else "casual")

# Инициализация истории чата
if "messages" not in st.session_state:
    st.session_state.messages = [{"role": "assistant", "content": "Здравствуйте! Я готов помочь. Опишите симптом или назовите лекарство."}]

# Отображение истории чата
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# Поле ввода сообщения (как в мессенджере)
if prompt := st.chat_input("Напишите ваш вопрос здесь..."):
    # Добавляем сообщение пользователя в историю и отображаем
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    # Получаем ответ от ИИ
    response = consult(prompt, mode=mode)
    
    # Добавляем ответ ИИ в историю и отображаем
    with st.chat_message("assistant"):
        st.markdown(response)
    st.session_state.messages.append({"role": "assistant", "content": response})

# Предупреждение внизу
st.sidebar.markdown("---")
st.sidebar.warning("?? Это не назначение врача. ИИ может ошибаться. Перед применением лекарств проконсультируйтесь со специалистом.")
